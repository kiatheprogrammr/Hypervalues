// Builds ideology_matrix.js, one score from -1 to +1 for every ideology and every value:  node tools/build_matrix.js
//   S  stated: the stance listed for the ideology in data.js (+1 strongly supports the value, -1 strongly opposes it)
//   E  estimated: the ideology lists nothing on the value, so the score is the model's guess from similar
//      ideologies (scoring.js, guessedValues), kept small (at most +-0.5) because it is a guess, not a position
//   N  none: no stance and no usable guess, so 0 (neutral, mixed or not clearly defined)
// A score can be corrected by hand: change it and its letter to M (manual). tools/check_matrix.js leaves M alone.
// Running this script again rewrites S, E and N entries and keeps every M entry.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const ctx = { localStorage: { getItem() { return null; }, setItem() {} }, console };
vm.createContext(ctx);
['data.js', 'scoring.js'].forEach(f => vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8').replace(/^const /gm, 'var '), ctx, { filename: f }));
const { HV } = ctx;

const CAP = 0.5;              // largest size of an estimate
const MIN = 0.05;             // smaller guesses count as "no usable guess"
const round = x => Math.round(x * 100) / 100;
const labels = [...new Set(Object.values(ctx.labelMapping))].sort((a, b) => a.localeCompare(b));
const values = [];
Object.keys(ctx.resultsMapping).forEach(cat => Object.keys(ctx.resultsMapping[cat]).forEach(v => values.push(v)));

let previous = null;
const file = path.join(root, 'ideology_matrix.js');
if (fs.existsSync(file)) {
    const text = fs.readFileSync(file, 'utf8');
    previous = JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1));
}

const rows = {};
const stats = { S: 0, E: 0, N: 0, M: 0 };
labels.forEach(label => {
    const order = HV.valueOrder(label);
    const byValue = {};
    Object.keys(order).forEach(cat => order[cat].forEach(item => { byValue[item.value] = item; }));
    const old = previous && previous.ideologies[label];
    const oldIndex = {};
    if (previous) previous.values.forEach((v, i) => { oldIndex[v] = i; });
    let scores = [], basis = '';
    values.forEach(v => {
        const kept = old && oldIndex[v] !== undefined && old.b[oldIndex[v]] === 'M';
        if (kept) { scores.push(old.s[oldIndex[v]]); basis += 'M'; stats.M++; return; }
        const item = byValue[v];
        if (item && item.listed) { scores.push(round(item.stance)); basis += 'S'; stats.S++; return; }
        const guess = item ? Math.max(-CAP, Math.min(CAP, round(item.stance))) : 0;
        if (Math.abs(guess) >= MIN) { scores.push(guess); basis += 'E'; stats.E++; } else { scores.push(0); basis += 'N'; stats.N++; }
    });
    rows[label] = { s: scores, b: basis };
});

const out = '// Generated by tools/build_matrix.js, checked by tools/check_matrix.js. One score from -1 to +1 for every ideology\n' +
    '// and value (s, in the order of "values"); b says where each score comes from: S stated in data.js, E estimated\n' +
    '// from similar ideologies, N none (0), M set by hand.\n' +
    'const IDEOLOGY_MATRIX = ' + JSON.stringify({ values, ideologies: rows }) + ';\n';
fs.writeFileSync(file, out);
console.log(`${labels.length} ideologies x ${values.length} values = ${labels.length * values.length} scores; stated ${stats.S}, estimated ${stats.E}, none ${stats.N}, manual ${stats.M}; ${(out.length / 1024).toFixed(0)} KB`);
